/**
 * Reads CESIUM_ION_TOKEN from makerbridge .env and writes
 * saveas-for-biz/js/cesium-token.local.js (gitignored).
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const saveasRoot = path.resolve(__dirname, "..");
const makerEnv = path.resolve(saveasRoot, "../makerbridge/.env");
const outFile = path.join(saveasRoot, "js/cesium-token.local.js");

function parseEnv(text) {
  const map = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
    if (!m) continue;
    map[m[1]] = m[2].replace(/^["']|["']$/g, "").trim();
  }
  return map;
}

if (!fs.existsSync(makerEnv)) {
  console.error("Missing", makerEnv);
  process.exit(1);
}
const env = parseEnv(fs.readFileSync(makerEnv, "utf8"));
const token = env.CESIUM_ION_TOKEN;
if (!token) {
  console.error("CESIUM_ION_TOKEN not in makerbridge .env");
  process.exit(1);
}
const body = `/**\n * Runtime Cesium ion token — DO NOT COMMIT.\n * Generated by scripts/inject-cesium-token.mjs\n */\nwindow.__CESIUM_ION_TOKEN = ${JSON.stringify(token)};\n`;
fs.writeFileSync(outFile, body);
console.log("Wrote", outFile);
